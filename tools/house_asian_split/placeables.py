#!/usr/bin/env python3
"""Classify the modular Asian house props and measure their authored poses.

Only independently shown root meshes are measured: fence Sub pieces remain
under the existing visibility rules. No export is changed. Rotation follows
Spring's T * bakedRotation * scriptRotation(-Z) * scale composition.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET
from stack_profiles import q

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'objects3d/house_asian.dae'
OUTPUT = ROOT / 'scripts/house_asian_placeable_catalog.lua'
# Identified from textured renders of the actual export, not numeric-name guesses.
ITEMS = {
    1: ('lighting', 'Three-arm street lamp'),
    2: ('public', '5G information terminal'),
    3: ('service', 'Hazard-marked barrel'),
    4: ('service', 'Dumpster'),
    5: ('service', 'Paired recycling bins'),
    6: ('clutter', 'Abandoned car'),
    7: ('clutter', 'Rubble mound'),
    8: ('market', 'Covered counter, tall'),
    9: ('lighting', 'Curved street lamp'),
    10: ('clutter', 'Garbage bags'),
    11: ('public', 'Freestanding display panel'),
    12: ('barrier', 'Traffic cone'),
    13: ('barrier', 'Blue warning bollards'),
    14: ('barrier', 'Red warning bollards'),
    15: ('public', 'Pharmacy sign'),
    16: ('barrier', 'Concrete traffic barrier'),
    17: ('market', 'Covered counter, low'),
    18: ('market', 'Market platform with canopy tables, warm'),
    19: ('market', 'Market platform with canopy tables, cool'),
    20: ('market', 'Lantern market stall'),
    21: ('market', 'Food kiosk on platform'),
    22: ('barrier', 'Mesh fence panel'),
    23: ('barrier', 'Patterned fence panel'),
    24: ('barrier', 'Screen fence panel'),
}


def generate(source=SOURCE):
    root = ET.parse(source).getroot()
    geos = {g.get('id'): g for g in root.find(q('library_geometries'))}
    nodes = {n.get('name'): n for s in root.find(q('library_visual_scenes')) for n in s.findall(q('node'))}
    lines = ['-- Generated by tools/house_asian_split/placeables.py; source-space bounds.',
             'return {', '    sourceHash = "' + hashlib.sha256(source.read_bytes()).hexdigest() + '",',
             '    scale = 0.0254,', '    pieces = {']
    for number, (category, label) in sorted(ITEMS.items()):
        name = 'Placeable' + str(number)
        node = nodes[name]
        m = [float(v) for v in node.findtext(q('matrix')).split()]
        mesh = geos[node.find(q('instance_geometry')).get('url')[1:]].find(q('mesh'))
        position_id = next(i.get('source')[1:] for i in mesh.find(q('vertices')).findall(q('input')) if i.get('semantic') == 'POSITION')
        positions = next(s for s in mesh.findall(q('source')) if s.get('id') == position_id)
        values = [float(v) for v in positions.findtext(q('float_array')).split()]
        vertices = list(zip(values[::3], values[1::3], values[2::3]))
        walkway = number in (1,2,3,4,5,9,10,11,12,13,14,15)
        lines.append('        [%s] = {category=%s, label=%s, walkway=%s, poses={' %
                     (json.dumps(name),json.dumps(category),json.dumps(label),str(walkway).lower()))
        for orientation in range(8):
            angle = -orientation * math.pi / 4
            c, s = math.cos(angle), math.sin(angle)
            points = []
            for x, y, z in vertices:
                x, y = c*x - s*y, s*x + c*y
                points.append(tuple(m[i]*x+m[i+1]*y+m[i+2]*z+m[i+3] for i in (0, 4, 8)))
            low = [min(v[i] for v in points) for i in range(3)]
            high = [max(v[i] for v in points) for i in range(3)]
            # Moves are parent-space offsets; keep authored pivot offsets in bounds.
            nums = lambda values: '{' + ','.join('%.4f' % v for v in values) + '}'
            # Lamp heads may overhang the road; their bases occupy the walkway.
            footprint = [p for p in points if p[1] <= low[1]+80] if category == 'lighting' else points
            foot_low = [min(p[i] for p in footprint) for i in range(3)]
            foot_high = [max(p[i] for p in footprint) for i in range(3)]
            lines.append('            {min=%s, max=%s, footMin=%s, footMax=%s},' %
                         (nums(low), nums(high), nums(foot_low), nums(foot_high)))
        lines.append('        }},')
    lines += ['    },', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        assert OUTPUT.read_text() == content, 'Stale placeable catalogue; inspect any new export transforms before regenerating'
        print('PASS: 24 classified placeables and all authored pose bounds match the export')
    else:
        OUTPUT.write_text(content)
        print(OUTPUT)
