"""Bake the principal standalone building meshes into 8x8 columns of 8-bit masks.
Run from the game root with Python, NumPy and SciPy. No runtime mesh readback.
"""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

import numpy as np
from scipy.ndimage import binary_fill_holes


def masks(mesh):
    vertices = mesh.find('{*}vertices/{*}input[@semantic="POSITION"]').get('source')[1:]
    source = mesh.find('{*}source[@id="%s"]' % vertices)
    stride = int(source.find('.//{*}accessor').get('stride', 3))
    points = np.fromstring(source.findtext('{*}float_array'), sep=' ').reshape(-1, stride)[:, :3]
    faces = []
    for part in mesh.findall('{*}triangles'):
        inputs = part.findall('{*}input')
        width = max(int(i.get('offset', 0)) for i in inputs) + 1
        vertex = int(next(i for i in inputs if i.get('semantic') == 'VERTEX').get('offset', 0))
        indices = np.fromstring(part.findtext('{*}p'), sep=' ', dtype=int).reshape(-1, width)
        faces.extend(indices[:, vertex].reshape(-1, 3))
    tri = points[np.asarray(faces)]
    lo, hi = tri.min(axis=(0, 1)), tri.max(axis=(0, 1))
    tri = (tri-lo) / np.maximum(hi-lo, 1e-9) * 8
    solid = np.zeros((8, 8, 8), dtype=bool)
    # Barycentric samples at <= 1/3 cell spacing include narrow and sloping walls.
    for a, b, c in tri:
        size = max(np.linalg.norm(a-b), np.linalg.norm(b-c), np.linalg.norm(c-a))
        steps = max(1, int(np.ceil(size*3)))
        u, v = np.tril_indices(steps+1)
        samples = a + (u-v)[:,None]/steps*(b-a) + v[:,None]/steps*(c-a)
        x,y,z = np.clip(samples.astype(int), 0, 7).T
        solid[x,y,z] = True
    solid = binary_fill_holes(solid)
    return ''.join('%02x' % mask for mask in (solid * (1 << np.arange(8))[None,:,None]).sum(axis=1).flat)


def bake(models, output):
    result = ['-- Generated by tools/house_icons/bake.py. Each byte is one vertical column.', 'return {']
    for model, pattern in [('house_asian_standalone', r'(arcology|project)\d+'),
                           ('house_asian2', r'house'), ('house_asian_comb', r'plate|base\d+')]:
        root = ET.parse(models/(model+'.dae'))
        for node in root.findall('.//{*}visual_scene//{*}node'):
            name = node.get('name', '').lower()
            if not re.fullmatch(pattern, name):
                continue
            inst = node.find('{*}instance_geometry')
            if inst is None:
                continue
            mesh = root.find('.//{*}geometry[@id="%s"]/{*}mesh' % inst.get('url')[1:])
            result.append('    %s = "%s",' % (name, masks(mesh)))
    output.write_text('\n'.join(result + ['}', '']))


if __name__ == '__main__':
    bake(Path('objects3d'), Path('luarules/gadgets/include/house_icon_bodies.lua'))
